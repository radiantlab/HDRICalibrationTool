#!/usr/bin/env node
/**
 * Regenerates `public/wasm/versions.json` from the fork checkouts.
 *
 * The versions cannot be read at runtime. None of the Radiance tools the
 * pipeline ships prints its version (only `ranimove1.c` and `rpiece.c` even
 * reference `VersionID`, and neither is in the build), and `dcraw_emu` prints
 * a usage banner with no LibRaw version in it. So the build is the only place
 * that knows, and this records what it knew.
 *
 * Run it whenever the `.wasm` artifacts are refreshed, from the same checkouts
 * they were built from. `public/wasm/README.md` has the build recipes.
 *
 *   node scripts/wasm-versions.mjs [--forks <dir>] [--check]
 *
 * `--forks` is the directory holding the Radiance, hdrgen and LibRaw
 * checkouts, defaulting to this repository's parent. `--check` exits non-zero
 * if the file on disk differs from what would be generated, without writing,
 * so CI can catch artifacts refreshed without their versions.
 */

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, "..");
const OUTPUT = join(REPO, "public", "wasm", "versions.json");

/** Pinned in each fork's CI. A different toolchain means different bytes. */
const EMSCRIPTEN = "6.0.4";

const args = process.argv.slice(2);
const checkOnly = args.includes("--check");
const forksIndex = args.indexOf("--forks");
const FORKS =
  forksIndex === -1 ? resolve(REPO, "..") : resolve(args[forksIndex + 1]);

function git(repo, ...rest) {
  return execFileSync("git", ["-C", join(FORKS, repo), ...rest], {
    encoding: "utf8",
  }).trim();
}

function describe(repo) {
  return {
    commit: git(repo, "rev-parse", "HEAD"),
    describe: git(repo, "describe", "--tags", "--always"),
  };
}

/** Strips the leading product name off `RADIANCE 6.1a`. */
const RADIANCE_PREFIX = /^RADIANCE\s+/;

/** `RADIANCE 6.1a`, the string Radiance's own build reads for its version. */
function radianceVersion() {
  return readFileSync(join(FORKS, "Radiance", "src", "rt", "VERSION"), "utf8")
    .trim()
    .replace(RADIANCE_PREFIX, "");
}

/** Assembled from the three defines rather than the macro, which is a C expression. */
function librawVersion() {
  const header = readFileSync(
    join(FORKS, "LibRaw", "libraw", "libraw_version.h"),
    "utf8"
  );
  const part = (name) => {
    const match = header.match(
      new RegExp(`#define\\s+LIBRAW_${name}_VERSION\\s+(\\d+)`)
    );
    if (!match) {
      throw new Error(`could not read LIBRAW_${name}_VERSION`);
    }
    return match[1];
  };
  return `${part("MAJOR")}.${part("MINOR")}.${part("PATCH")}`;
}

const versions = {
  $comment:
    "Generated by scripts/wasm-versions.mjs. Regenerate whenever the .wasm " +
    "artifacts in this directory are rebuilt; they describe those artifacts, " +
    "not whatever is checked out now.",
  emscripten: EMSCRIPTEN,
  tools: {
    dcraw_emu: {
      ...describe("LibRaw"),
      repository: "radiantlab/LibRaw",
      upstream: "LibRaw/LibRaw",
      version: librawVersion(),
    },
    hdrgen: {
      ...describe("hdrgen"),
      repository: "radiantlab/hdrgen",
      version: git("hdrgen", "describe", "--tags", "--always").replace(
        /^v/,
        ""
      ),
    },
    radiance: {
      ...describe("Radiance"),
      repository: "radiantlab/Radiance",
      upstream: "LBNL-ETA/Radiance",
      version: radianceVersion(),
    },
  },
};

const serialised = `${JSON.stringify(versions, null, 2)}\n`;

if (checkOnly) {
  let existing = "";
  try {
    existing = readFileSync(OUTPUT, "utf8");
  } catch {
    console.error(
      `${OUTPUT} does not exist. Run: node scripts/wasm-versions.mjs`
    );
    process.exit(1);
  }
  if (existing !== serialised) {
    console.error(
      `${OUTPUT} is stale. Run: node scripts/wasm-versions.mjs\n` +
        "If the .wasm artifacts were not rebuilt, check that --forks points at " +
        "the checkouts they came from rather than newer ones."
    );
    process.exit(1);
  }
  console.log("versions.json matches the fork checkouts");
} else {
  writeFileSync(OUTPUT, serialised);
  console.log(`wrote ${OUTPUT}`);
  console.log(serialised);
}
